#!/usr/bin/env node
// Protect the same observation -> optional check -> mismatch -> inspect -> repair journey
// through the integrated Simulate table and requested Details drawer.
import { assert, clickVerifyRun, loadStarterProject, runIdeGate, visible } from './_gateHarness.mjs';
import { waitForVerifyResult } from './_verifyStatus.mjs';

await runIdeGate('IDE verify workbench contract satisfied', async ({ page, baseUrl }) => {
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.addInitScript(() => localStorage.setItem('rb-onboarding-v1-seen', '1'));
  await page.goto(`${baseUrl}/`, { waitUntil: 'domcontentloaded' });
  await page.locator('[data-testid="ide-root"]').waitFor();
  await loadStarterProject(page);
  await page.locator('[data-testid="mode-button-verify"]').click();
  await page.locator('[data-testid="ide-verify-panel"]').waitFor();
  const details = page.locator('[data-testid="ide-verify-details"]');
  await details.click();
  await page.locator('[data-testid="ide-sim-clear-checks"]').click();
  await details.click();
  await page.locator('[data-testid="ide-verify-view-table"]').click();
  const table = page.locator('[data-testid="ide-case-lab-table"]');
  await table.waitFor({ state: 'visible' });
  const authoredCheckCount = async () => (await table.locator('[data-testid^="ide-case-lab-exp-"]').allTextContents())
    .filter(value => value.trim() === '0' || value.trim() === '1').length;
  assert(await authoredCheckCount() === 0, 'clearing optional checks must leave zero authored expectations and a runnable observation');
  await clickVerifyRun(page);
  await waitForVerifyResult(page);
  const summary = page.locator('[data-testid="ide-verify-summary-status"]');
  assert(/observation|stimulus|recorded|simulation/i.test(await summary.textContent()), 'run without expected outputs must record observations without a passing check verdict');
  await page.locator('[data-testid="ide-verify-view-table"]').click();
  await table.waitFor({ state: 'visible' });
  const expected = table.locator('[data-testid^="ide-case-lab-exp-"]').first();
  assert(await visible(expected), 'optional checks must remain directly editable after a recording');
  assert(/0.*1.*none/i.test(await expected.getAttribute('title')), 'expected value control must explain clearing a check');
  const observed = (await expected.locator('xpath=../following-sibling::td[1]').textContent()).trim();
  assert(observed === '0' || observed === '1', 'recorded output must retain a binary observed value');
  const setExpected = async value => {
    for (let i = 0; i < 3 && (await expected.textContent()).trim() !== value; i++) await expected.click();
    assert((await expected.textContent()).trim() === value, `expected output must accept ${value}`);
  };
  await setExpected(observed === '0' ? '1' : '0');
  assert(await authoredCheckCount() === 1, 'authored expectation must add exactly one optional check');
  await clickVerifyRun(page);
  await waitForVerifyResult(page);
  await page.waitForFunction(() => /checks failing|checks need review|assertions differ/i.test(document.querySelector('[data-testid="ide-verify-summary-status"]')?.textContent || ''), undefined, { timeout: 5000 });
  assert(/checks failing|checks need review|assertions differ/i.test(await summary.textContent()), 'opposite expected value must produce a failed comparison');
  assert(await visible(table), 'a failed run must retain the editable cases');
  const failedCell = table.locator('[data-testid^="ide-case-lab-obs-"][aria-label$=", mismatch"]').first();
  await failedCell.waitFor({ state: 'visible' });
  const failedRow = failedCell.locator('xpath=ancestor::tr');
  assert(await visible(failedRow), 'failed recording must identify its precise mismatching observation in the editable table');
  const failedTick = (await failedRow.getAttribute('data-testid')).replace('ide-case-lab-row-', '');
  await failedCell.click();
  assert(await failedRow.getAttribute('aria-selected') === 'true', 'selecting a failing case must retain its concrete tick');
  const selectedResult = page.locator('[data-testid="ide-verify-selected-result"]');
  assert(await selectedResult.getAttribute('data-mismatch') === 'true', 'the selected result must identify the exact recorded mismatch');
  await page.locator('[data-testid="ide-verify-view-waveform"]').click();
  assert(await selectedResult.getAttribute('data-tick') === failedTick, 'case inspection must follow the same tick into the recording');
  const waveform = page.locator('[data-testid="ide-verify-waveform-preview"]');
  await waveform.waitFor({ state: 'visible' });
  const bounds = await waveform.boundingBox();
  assert(bounds.width >= 480 && bounds.height >= 210, `recording must remain readable (${bounds.width}x${bounds.height})`);
  const tools = page.locator('[data-testid="ide-verify-waveform-tools"]');
  assert(await visible(tools), 'View and measure must be reachable from recording');
  assert(!await visible(tools.locator('[data-testid="ide-verify-waveform-tools-panel"]')), 'measurement tools must open only on request');
  await tools.locator('summary').click();
  assert(await visible(page.locator('[data-testid="ide-verify-set-cursor-a"]')), 'requested measurement tools must reveal cursor controls');
  await tools.locator('summary').click();
  await details.click();
  await page.locator('[data-testid="ide-verify-analysis-tab-nav"]').waitFor({ state: 'visible' });
  await page.locator('[data-testid="ide-verify-analysis-tab-nav"]').getByRole('button', { name: 'Checks', exact: true }).click();
  const mismatchRows = page.locator('[data-testid="ide-verify-mismatch-list"] tbody tr');
  assert(await mismatchRows.count() >= 1, 'Details must retain concrete mismatch rows');
  const tick = (await mismatchRows.first().locator('button').first().textContent()).trim();
  await mismatchRows.first().locator('button').first().click();
  assert(await selectedResult.getAttribute('data-tick') === tick.replace(/^t/, ''), 'mismatch selection must move the recording cursor to the same tick');
  await details.click();
  await page.locator('[data-testid="ide-verify-view-table"]').click();
  await setExpected(observed);
  await clickVerifyRun(page);
  await waitForVerifyResult(page);
  await page.waitForFunction(() => /checks passing/i.test(document.querySelector('[data-testid="ide-verify-summary-status"]')?.textContent || ''), undefined, { timeout: 5000 });
  assert(/checks passing/i.test(await summary.textContent()), 'repairing the expected output must yield passing checks');
  assert(await page.locator('[data-testid="ide-verify-three-panel-left"], [data-testid="ide-verify-three-panel-right"]').count() === 0, 'retired inline failure rails must not reclaim the recording workspace');
});
