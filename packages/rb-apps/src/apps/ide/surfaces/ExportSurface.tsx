function toMappingEntryKey(entry: {
  id: string;
  nodeId: string;
  port: string;
  label?: string;
}): string {
  const label = (entry.label ?? '').trim();
  if (label.length > 0) return toPortKey(label);
  const id = (entry.id ?? '').trim();
  if (id.length > 0) return toPortKey(id);
  return toPortKey(`${entry.nodeId}.${entry.port}`);
}

