function collectMappedProjectPortKeys(project: RBProject): Set<string> {
  const keys = new Set<string>();
  const liveIoNodeLabels = buildLiveIoNodeLabelIndex(project);
  for (const entry of project.ioMapping?.inputs ?? []) {
    keys.add(toMappingEntryKey(entry, liveIoNodeLabels));
  }
  for (const entry of project.ioMapping?.outputs ?? []) {
    keys.add(toMappingEntryKey(entry, liveIoNodeLabels));
  }
  return keys;
}

function applyPinOverridesToProject(
  project: RBProject,
  overrides: Record<string, string>
): RBProject {
  if (!project.ioMapping) return project;
  const liveIoNodeLabels = buildLiveIoNodeLabelIndex(project);

  const applyEntries = (entries: NonNullable<RBProject['ioMapping']>['inputs']) =>
    entries.map((entry) => {
      const override = (overrides[toMappingEntryKey(entry, liveIoNodeLabels)] ?? entry.pin ?? '').trim();
      return {
        ...entry,
        pin: override.length > 0 ? override : undefined,
      };
    });

  return {
    ...project,
    ioMapping: {
      inputs: applyEntries(project.ioMapping.inputs ?? []),
      outputs: applyEntries(project.ioMapping.outputs ?? []),
    },
  };
}

function buildEvidenceDiagnostics(
  verifyResult: ProjectHealthVerifyResult | undefined,
  dirtySinceVerify: boolean,
  vectorsAreAutoGenerated = false,
  verifyQualification?: RuntimeVerifyRun['qualification']
): ExportDiagnosticView[] {
  const diagnostics: ExportDiagnosticView[] = [];
  const verifyState = deriveProjectVerifyState({
    lastVerify: verifyResult,
    dirtySinceVerify,
  });

  if (!verifyResult) {
    diagnostics.push(createEvidenceDiagnostic({
      code: 'RBEV1000',
      message: 'No comparison run found. Export files are still available, but no expected-output evidence has been recorded yet.',
      fix: 'Open Verify when you want to compare expected outputs against the live design before relying on the package as final hardware evidence.',
      severity: 'warning',
    }));
    return diagnostics;
  }

  if (dirtySinceVerify) {
    diagnostics.push(createEvidenceDiagnostic({
      code: 'RBEV1002',
      message: 'Design, testbench, or mapping changed since the last Verify run. Export files remain available, but that Verify evidence is stale for the current handoff.',
      fix: 'Open Verify and rerun simulation or compare when you want current evidence for this export.',
      severity: 'warning',
    }));
  } else if (verifyState === 'trace') {
    diagnostics.push(createEvidenceDiagnostic({
      code: 'RBEV1004',
      message: 'Latest Verify activity recorded a trace-only run. Export files are still available, but expected-output comparison has not been confirmed yet.',
      fix: 'Open Verify and run Compare checks when you want current evidence for trusted export.',
      severity: 'warning',
    }));
  }

  if (!dirtySinceVerify && verifyResult.status !== 'pass') {
    const isStarterFail = vectorsAreAutoGenerated;
    diagnostics.push(createEvidenceDiagnostic({
      code: 'RBEV1001',
      message: isStarterFail
        ? 'Ran with auto-generated starter vectors - scenario not yet authored. Export is available, but the comparison evidence is still starter-grade.'
        : typeof verifyResult.failingTick === 'number'
          ? `Latest comparison run differed at tick ${verifyResult.failingTick}. Export files remain available.`
          : 'Latest comparison run differed from observed outputs. Export files remain available.',
      fix: isStarterFail
        ? 'Author a real test scenario in Verify (not starter vectors) before treating this export as evidence-grade.'
        : 'Open Verify, inspect the first difference, then rerun Compare when you want refreshed evidence.',
      severity: 'warning',
    }));
  }

  if (verifyQualification === 'incomplete-mapping') {
    diagnostics.push(createEvidenceDiagnostic({
      code: 'RBEV1003',
      message:
        'Latest comparison run matched the logic, but required output mapping was incomplete. Export files are available, but hardware interpretation is still incomplete.',
      fix:
        'Complete the live output pin mapping, then rerun Compare when you want refreshed evidence against the current design.',
      severity: 'warning',
    }));
  }

  return diagnostics;
}

