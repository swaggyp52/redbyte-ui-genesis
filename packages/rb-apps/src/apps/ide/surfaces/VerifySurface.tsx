function buildFailureCaseKey(
  tick: number,
  signal: string,
  vectorId?: string,
  caseIndex?: number
): string {
  return [
    tick,
    normalizeFieldId(signal),
    signal,
    vectorId?.trim() || 'no-vector',
    Number.isFinite(caseIndex) ? String(caseIndex) : 'no-case',
  ].join(':');
}

